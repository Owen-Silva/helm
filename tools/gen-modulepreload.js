// Generates the <link rel="modulepreload"> block in ui/index.html from the static import graph, so the
// browser fetches every startup module in parallel instead of discovering them one level at a time
// (each module is only requested after its parent has been downloaded and parsed).
// Re-run after adding, removing or renaming a UI module that loads at startup:
//   node tools/gen-modulepreload.js            rewrite the block in ui/index.html
//   node tools/gen-modulepreload.js --check    exit 1 if the block is stale (prints the diff)
//   node tools/gen-modulepreload.js --list     print the module list only
//   node tools/gen-modulepreload.js --remove   take the block out again
// NOT APPLIED as of 2026-10-08: tools/bench-startup.js measured no gain (see docs/PROTOCOL.md, lane git-export).
// Static `import ... from`, bare `import '...'` and `export ... from` count; dynamic import() does not
// (those load on demand and stay out of the startup path). Bare specifiers resolve through the
// page's import map. CSP: the links are same-origin ('self'), so script-src 'self' already allows them.
// Owner: lane git-export.
const fs = require('fs');
const path = require('path');

const UI = path.join(__dirname, '..', 'ui');
const INDEX = path.join(UI, 'index.html');
const START = '<!-- modulepreload:start (generated by tools/gen-modulepreload.js; do not edit by hand) -->';
const END = '<!-- modulepreload:end -->';

function stripComments(src) {
  // Good enough for this codebase: drop /* */ blocks and // line comments that start a line or follow
  // whitespace (keeps "http://" inside strings intact).
  return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[\s;])\/\/[^\n]*/g, '$1');
}

function staticImports(src) {
  const s = stripComments(src);
  const out = [];
  const re = /(?:^|[;\n}])\s*(?:import\s*(?:[\w*$\s{},]+?\s*from\s*)?|export\s*(?:\*(?:\s+as\s+[\w$]+)?|\{[^}]*\})\s*from\s*)['"]([^'"\n]+)['"]/g;
  let m;
  while ((m = re.exec(s))) out.push(m[1]);
  return out;
}

function readIndex() {
  const html = fs.readFileSync(INDEX, 'utf8');
  const mapJson = /<script type="importmap">([\s\S]*?)<\/script>/.exec(html);
  const imports = mapJson ? JSON.parse(mapJson[1]).imports || {} : {};
  const entries = [...html.matchAll(/<script type="module" src="([^"]+)"><\/script>/g)].map((m) => m[1]);
  return { html, imports, entries };
}

// URL path ("/shell/header.js") -> module graph in breadth-first order (entries first).
function graph() {
  const { imports, entries } = readIndex();
  const seen = new Set();
  const order = [];
  const queue = [...entries];
  const missing = [];
  while (queue.length) {
    const url = queue.shift();
    if (seen.has(url)) continue;
    seen.add(url);
    const file = path.join(UI, ...url.split('/').filter(Boolean));
    let src;
    try { src = fs.readFileSync(file, 'utf8'); } catch { missing.push(url); continue; }
    order.push(url);
    for (const spec of staticImports(src)) {
      let next;
      if (Object.prototype.hasOwnProperty.call(imports, spec)) next = imports[spec];
      else if (spec.startsWith('./') || spec.startsWith('../') || spec.startsWith('/')) next = new URL(spec, 'http://x' + url).pathname;
      else { missing.push(`${url} -> ${spec} (bare, not in import map)`); continue; }
      if (!seen.has(next)) queue.push(next);
    }
  }
  return { order, entries, missing };
}

function block(order, entries) {
  // The entry scripts are requested by their own <script> tags; preload everything below them.
  const list = order.filter((u) => !entries.includes(u));
  return [START, ...list.map((u) => `  <link rel="modulepreload" href="${u}">`), `  ${END}`].join('\n');
}

// html with a fresh block (inserted right after the import map: a modulepreload of a module with bare
// imports must see the map first), and html with the block removed.
function withBlock(html) {
  const { order, entries } = graph();
  const fresh = block(order, entries);
  if (html.includes(START) && html.includes(END)) return html.slice(0, html.indexOf(START)) + fresh + html.slice(html.indexOf(END) + END.length);
  const at = html.indexOf('</script>', html.indexOf('<script type="importmap">')) + '</script>'.length;
  return html.slice(0, at) + '\n  ' + fresh + html.slice(at);
}
function withoutBlock(html) {
  if (!html.includes(START)) return html;
  return html.slice(0, html.indexOf(START)).replace(/\s+$/, '') + html.slice(html.indexOf(END) + END.length);
}

function main() {
  const { order, entries, missing } = graph();
  if (missing.length) { console.error('unresolved:\n  ' + missing.join('\n  ')); process.exitCode = 1; }
  if (process.argv.includes('--list')) { console.log(order.join('\n')); console.log(`${order.length} modules`); return; }
  const { html } = readIndex();
  if (process.argv.includes('--remove')) { const next = withoutBlock(html); if (next !== html) fs.writeFileSync(INDEX, next); console.log(next !== html ? 'removed the modulepreload block' : 'no block to remove'); return; }
  const next = withBlock(html);
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('ui/index.html modulepreload block is missing or stale: run node tools/gen-modulepreload.js'); process.exitCode = 1; }
    else console.log(`modulepreload block up to date (${order.length - entries.length} links)`);
    return;
  }
  if (next !== html) fs.writeFileSync(INDEX, next);
  console.log(`${next !== html ? 'wrote' : 'unchanged'} ${order.length - entries.length} modulepreload links (${order.length} modules incl. ${entries.length} entries)`);
}

if (require.main === module) main();
module.exports = { staticImports, graph, block, withBlock, withoutBlock, START, END };
